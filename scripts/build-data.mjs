// Generates src/data/gallery.generated.ts + responsive variants + 3D textures from the mirrored assets.
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1")), "..");
const pub = (...p) => path.join(ROOT, "public", ...p);
const WIDTHS = [480, 960];

const ART_TITLES = [
  "A4 Crepe Paper 20 Sheets 36 GSM","Craft Cylinder 6 Inch x 0.35 Inch Pack of 12 Pcs","Crepe Paper Streamer 12 Pcs","A4 Jute Sheet 10 Sheet",
  "Crepe Paper Streamer 24 Pcs","Crepe 12 Fold","Crepe Paper Roll 50 cm x 200 cm (500mm x 2000mm)","A4 Colour Paper 48 Sheets 75 GSM",
  "A4 Glitter Paper - 10 Sheets","School Labels 6 Sheets 48 Labels","Laminated Kraft Paper Roll - 33 cm x 8 Meter 80 GSM KK",
  "A4 Colour Board 10 Sheets 10 Colour 175 GSM","Party Popper - 40 cm","Birthday Caps - Glitter 10 Pcs Pack","Happy Birthday Kit - 35 Pcs Set",
  "Thermacol Balls - 8 Grams Pack","Printed Gift Carry Bag Medium","A4 Ruled Punched Paper - 50 Sheets 75 GSM","Alphabet Colouring Book No of Pages 16",
  "Birds Colouring Book No of Pages 16","Animals Colouring Book No of Pages 16","Fruits Colouring Book No of Pages 16","Vegetables Colouring Book No of Pages 16",
  "Flowers Colouring Book No of Pages 16","Vehicles Colouring Book No of Pages 16","Dot to Dot Colouring Book No of Pages 16","Fun Art Colouring No of Pages 16",
  "Crayons Gallery Colouring No of Pages 24","Jumbo Funtime Colouring Book No of Pages 80","A3 Drawing Book 20 Sheets White 40 Pages 175 GSM",
  "A3 Drawing Book Multicolour 20 Sheets 40 Pages 175 GSM","A3 Black Drawing Book 20 Sheets 40 Pages 175 GSM","A4 Black Drawing Book 20 Sheets 40 Pages 175 GSM",
  "A4 Sketch Book / Drawing Book White 40 Pages 175 GSM","A4 Graph Paper Pad 50 Sheets 70 GSM","A4 Drawing Book / Colour Card Stock Multicolour 20 Sheets",
  "Gift Carry Bag Gold/Silver/Rosegold Small","A4 Cut & Paste 10 Sheets 160 GSM","A5 Scrap Book 120 GSM 32 Pages with Cover",
  "Laminated Kraft Paper Roll - 33 cm x 8 Meter 80 GSM SS","School Labels 10 Sheets 160 Labels","A4 Assorted Craft Work 32 Sheets",
  "Colour Chart Paper 100 cm x 70 cm 180 GSM","A4 Tracing Paper 25 Sheets 65 GSM","Gift Wrapping Sheet 50 cm x 70 cm 25 Sheets Pack","Shreded Tissue Paper",
];
const COLLECTIONS = [
  { id: "camlin", prefix: "camlin" }, { id: "flexoffice", prefix: "flexoffice" }, { id: "pelikan", prefix: "pelikan" },
  { id: "english-notebook", prefix: "eng" }, { id: "art-craft", prefix: "art" },
];

const files = (await fs.readdir(pub("gallery"))).filter(f => /\.(webp|jpe?g)$/.test(f));
const items = [];
for (const c of COLLECTIONS) {
  const mine = files.filter(f => new RegExp("^" + c.prefix + "[0-9]+[.]").test(f)).sort((a, b) => parseInt(a.replace(/\D/g, "")) - parseInt(b.replace(/\D/g, "")));
  for (const f of mine) {
    const n = parseInt(f.replace(/\D/g, ""));
    const src = pub("gallery", f);
    let img;
    try { img = sharp(src); var meta = await img.metadata(); } catch { console.warn("skip", f); continue; }
    const base = f.replace(/\.(webp|jpe?g)$/, "");
    for (const w of WIDTHS) {
      const out = pub("gallery", `w${w}`, `${base}.webp`);
      try { await fs.access(out); } catch {
        await fs.mkdir(path.dirname(out), { recursive: true });
        await sharp(src).resize({ width: Math.min(w, meta.width) }).webp({ quality: 78 }).toFile(out);
      }
    }
    const { dominant } = await sharp(src).stats();
    const hex = "#" + [dominant.r, dominant.g, dominant.b].map(v => v.toString(16).padStart(2, "0")).join("");
    items.push({
      id: `${c.id}-${n}`, collection: c.id, n, file: base, w: meta.width, h: meta.height, color: hex,
      ...(c.id === "art-craft" && ART_TITLES[n - 1] ? { title: ART_TITLES[n - 1] } : {}),
    });
  }
}
await fs.mkdir(path.join(ROOT, "src/data"), { recursive: true });
await fs.writeFile(path.join(ROOT, "src/data/gallery.generated.ts"),
  `// AUTO-GENERATED by scripts/build-data.mjs — do not edit by hand.\nimport type { GalleryItem } from "./types";\n\nexport const GALLERY: GalleryItem[] = ${JSON.stringify(items)};\n`);
console.log("gallery items", items.length);

// 3D textures: real BnB notebook covers, trimmed of their white studio background.
await fs.mkdir(pub("textures"), { recursive: true });
for (const [f, out] of [["eng1.webp", "notebook-orange.jpg"], ["eng27.webp", "spiral-1.jpg"], ["eng29.webp", "spiral-2.jpg"], ["eng30.webp", "spiral-3.jpg"], ["eng25.webp", "notebook-white.jpg"]]) {
  const t = await sharp(pub("gallery", f)).flatten({ background: "#fff" }).trim({ threshold: 30 }).toBuffer();
  await sharp(t).resize(512, 704, { fit: "cover" }).jpeg({ quality: 82 }).toFile(pub("textures", out));
}
// (One-off: the large brand PNGs were converted to 720px webp on first run.)
console.log("done");
